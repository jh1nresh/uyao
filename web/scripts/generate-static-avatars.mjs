import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const avatarRoot = path.join(webRoot, "components/avatar-lab");
const outputRoot = path.join(avatarRoot, "static");

const parseStringConstant = (source, name) => {
  const prefix = `export const ${name} = `;
  const line = source.split("\n").find((candidate) => candidate.startsWith(prefix));
  if (!line) throw new Error(`Missing ${name}`);
  return JSON.parse(line.slice(prefix.length));
};

const parseAvatarData = async (name) => {
  const source = await readFile(path.join(avatarRoot, `${name}.avatar.ts`), "utf8");
  const match = source.match(/export const avatarData = (\{.*\}) as const satisfies AvatarData/s);
  if (!match) throw new Error(`Could not parse ${name}.avatar.ts`);
  return JSON.parse(match[1]);
};

const parseObjectConstant = (source, name) => {
  const match = source.match(new RegExp(`export const ${name} = (\\{[\\s\\S]*?\\n\\}) as const;`));
  if (!match) throw new Error(`Could not parse ${name}`);
  return Function(`"use strict"; return (${match[1]});`)();
};

const runtimeSource = await readFile(path.join(avatarRoot, "avatar-runtime.ts"), "utf8");
const engineSource = parseStringConstant(runtimeSource, "ENGINE_SOURCE");
const engine = Function(`${engineSource}\nreturn AvatarProceduralEngine;`)();

const sprout = await parseAvatarData("sprout");
const footerSource = await readFile(
  path.join(webRoot, "components/landing/footerSproutData.ts"),
  "utf8",
);
const footerExpression = parseObjectConstant(
  footerSource,
  "BIBLE_STRONG_SPROUT_IDLE_EXPRESSIONS",
);
const footerAnimation = parseObjectConstant(footerSource, "BIBLE_STRONG_SPROUT_IDLE");
const eyeCentreY = -38;
const eyeHeightScale = 0.79;
const eyeSpacingScale = 0.92;
const arcForCentre = (centreY) => 120 * Math.asin(centreY / 120);
const liftEyes = (expression) => ({
  ...expression,
  heightLeft: expression.heightLeft * eyeHeightScale,
  heightRight: expression.heightRight * eyeHeightScale,
  positionYLeft: expression.positionYLeft + arcForCentre(eyeCentreY),
  positionYRight: expression.positionYRight + arcForCentre(eyeCentreY),
  spacing: expression.spacing * eyeSpacingScale,
});
const footerSprout = {
  ...sprout,
  expressions: Object.fromEntries(
    Object.entries({ ...sprout.expressions, ...footerExpression }).map(([id, expression]) => [
      id,
      liftEyes(expression),
    ]),
  ),
  animations: { ...sprout.animations, idle: footerAnimation },
};

const avatars = [
  ["sprout", "Sprout", sprout, "listening"],
  ["sapling", "Sapling", await parseAvatarData("sapling"), "searching"],
  ["flame", "Flame", await parseAvatarData("flame"), "thinking"],
  ["pepper", "Pepper", await parseAvatarData("pepper"), "idle"],
  ["footer-sprout", "FooterSprout", footerSprout, "idle"],
];

const jsxPath = (value) => JSON.stringify(value);
const renderComponent = (componentName, data, animationName) => {
  const animation = data.animations[animationName];
  const expression = data.expressions[animation.steps[0].expressionId];
  const pose = engine.poseFromExpression(expression);
  const geometry = engine.renderAvatar(pose, data.avatar.surface, 1, {
    includeWire: false,
    bodyNodes: data.avatar.bodyNodes,
    eyeOffset: { x: 0, y: 0 },
  });
  const body = expression.bodyColor || data.avatar.colors.body;
  const eyes = expression.eyeColor || data.avatar.colors.eyes;
  const backPaths = geometry.backPaths
    .map((value, index) => `          <path key="back-${index}" d={${jsxPath(value)}} fill="${body}" />`)
    .join("\n");
  const frontPaths = geometry.frontPaths
    .map((value, index) => `          <path key="front-${index}" d={${jsxPath(value)}} fill="${body}" />`)
    .join("\n");

  return `// Generated by scripts/generate-static-avatars.mjs. Do not edit directly.
import { useId, type CSSProperties } from "react";

type ${componentName}StaticProps = {
  size?: number | string;
  className?: string;
  style?: CSSProperties;
};

export function ${componentName}Static({
  size = 240,
  className,
  style,
}: ${componentName}StaticProps) {
  const clipId = \`avatar-static-\${useId().replaceAll(":", "")}\`;
  const dimension = typeof size === "number" ? \`\${size}px\` : size;

  return (
    <span className={className} style={{ display: "inline-block", width: dimension, height: dimension, ...style }}>
      <svg viewBox="-150 -150 300 300" role="img" aria-label="${data.avatar.name}" style={{ display: "block", width: "100%", height: "100%", overflow: "visible" }}>
        <defs>
          <clipPath id={clipId}>
            <path d={${jsxPath(geometry.headPath)}} />
          </clipPath>
        </defs>
        <g>
${backPaths}
          <path d={${jsxPath(geometry.headPath)}} fill="${body}" />
          <g clipPath={\`url(#\${clipId})\`}>
            <path d={${jsxPath(geometry.leftPath)}} fill="${eyes}"${geometry.leftVisible ? "" : ' style={{ display: "none" }}'} />
            <path d={${jsxPath(geometry.rightPath)}} fill="${eyes}"${geometry.rightVisible ? "" : ' style={{ display: "none" }}'} />
          </g>
${frontPaths}
        </g>
      </svg>
    </span>
  );
}
`;
};

await mkdir(outputRoot, { recursive: true });
for (const [fileName, componentName, data, animationName] of avatars) {
  await writeFile(
    path.join(outputRoot, `${fileName}.svg.tsx`),
    renderComponent(componentName, data, animationName),
  );
}
